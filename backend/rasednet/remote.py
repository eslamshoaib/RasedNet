"""Credential vault + execution of guidance commands (remotely over WinRM, or on the scanner).

Only commands generated by ``rasednet.remediation`` can be executed — never free text. Placeholder
values supplied by the operator are validated against strict patterns before substitution.
"""

from __future__ import annotations

import ipaddress
import os
import re
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

from cryptography.fernet import Fernet, InvalidToken

from rasednet.config import Settings
from rasednet.i18n import get_lang, tr

MAX_OUTPUT = 64 * 1024

# Commands that open GUI programs or interactive sessions are shown, never executed by RasedNet.
NON_EXECUTABLE_PREFIXES = ("mstsc", "explorer", "compmgmt", "Enter-PSSession", "ssh ", "ftp ", "telnet", "Start-Process",
                           "sqlcmd", "mysql ", "psql ", "mongosh", "redis-cli", "vlc ")


class VaultError(Exception):
    pass


class RemoteError(Exception):
    pass


# --- vault -------------------------------------------------------------------------------


def _fernet(settings: Settings) -> Fernet:
    if not settings.secret_key:
        raise VaultError(tr("خزنة بيانات الدخول غير مفعلة: لم يُضبط RASEDNET_SECRET_KEY. أنشئ مفتاحاً بالأمر: python -m rasednet gen-secret-key", "The credential vault is not enabled: RASEDNET_SECRET_KEY is not set. Create a key with: python -m rasednet gen-secret-key"))
    try:
        return Fernet(settings.secret_key.encode("ascii"))
    except (ValueError, UnicodeEncodeError) as exc:
        raise VaultError(tr("قيمة RASEDNET_SECRET_KEY غير صالحة", "Invalid RASEDNET_SECRET_KEY value")) from exc


def encrypt_secret(settings: Settings, secret: str) -> str:
    return _fernet(settings).encrypt(secret.encode("utf-8")).decode("ascii")


def decrypt_secret(settings: Settings, token: str) -> str:
    try:
        return _fernet(settings).decrypt(token.encode("ascii")).decode("utf-8")
    except InvalidToken as exc:
        raise VaultError(tr("تعذر فك تشفير بيانات الدخول (تغير مفتاح الخزنة؟)", "Could not decrypt the credential (did the vault key change?)")) from exc


# --- placeholders ------------------------------------------------------------------------

PLACEHOLDERS: dict[str, tuple[str, str]] = {
    # placeholder text in the command : (parameter name, Arabic description)
    "<ServiceName>": ("service_name", tr("اسم خدمة ويندوز (Name)", "Windows service name (Name)")),
    "ADMIN_SUBNET": ("subnet", tr("شبكة الإدارة بصيغة CIDR", "Management subnet in CIDR")),
    "UNTRUSTED_SUBNET": ("subnet", tr("الشبكة غير الموثوقة بصيغة CIDR", "Untrusted subnet in CIDR")),
    "<unit-name>": ("unit_name", tr("اسم وحدة systemd (مثل nginx.service)", "systemd unit name (e.g. nginx.service)")),
}
_UNIT_NAME_RE = re.compile(r"^[A-Za-z0-9@._:\-]{1,120}$")
_SERVICE_NAME_RE = re.compile(r"^[A-Za-z0-9_.\-$]{1,80}$")


def required_params(command: str) -> list[dict[str, str]]:
    seen: dict[str, str] = {}
    for placeholder, (param, desc) in PLACEHOLDERS.items():
        if placeholder in command:
            seen[param] = desc
    return [{"name": k, "label_ar": v} for k, v in seen.items()]


def fill_placeholders(command: str, params: dict[str, str]) -> str:
    for placeholder, (param, desc) in PLACEHOLDERS.items():
        if placeholder not in command:
            continue
        value = (params.get(param) or "").strip()
        if not value:
            raise RemoteError((f"Required: {desc}" if get_lang()=="en" else f"يجب إدخال: {desc}"))
        if param == "service_name":
            if not _SERVICE_NAME_RE.match(value):
                raise RemoteError(tr("اسم الخدمة غير صالح (أحرف إنجليزية وأرقام و _ . - $ فقط)", "Invalid service name (letters, digits and _ . - $ only)"))
        elif param == "unit_name":
            if not _UNIT_NAME_RE.match(value):
                raise RemoteError(tr("اسم الوحدة غير صالح", "Invalid unit name"))
        elif param == "subnet":
            try:
                value = str(ipaddress.ip_network(value, strict=False))
            except ValueError as exc:
                raise RemoteError(tr("صيغة الشبكة غير صالحة، مثال: 10.0.10.0/24", "Invalid subnet format, e.g. 10.0.10.0/24")) from exc
        command = command.replace(placeholder, value)
    return command


def is_executable(command: str) -> bool:
    return not command.strip().startswith(NON_EXECUTABLE_PREFIXES)


# --- execution -----------------------------------------------------------------------------


@dataclass
class ExecResult:
    output: str
    had_errors: bool


def _truncate(text: str) -> str:
    return text if len(text) <= MAX_OUTPUT else text[:MAX_OUTPUT] + ("\n… [output truncated]" if get_lang()=="en" else "\n… [تم اقتطاع المخرجات]")


def run_local_powershell(script: str, timeout: int) -> ExecResult:
    """Run a network check on the scanner host itself (it is the administrator's machine)."""
    if sys.platform != "win32":
        raise RemoteError(tr("التحقق المحلي متاح على خادم ويندوز فقط", "Local verification is available on a Windows server only"))
    ps = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "WindowsPowerShell", "v1.0", "powershell.exe")
    try:
        done = subprocess.run(
            [ps, "-NoProfile", "-NonInteractive", "-Command",
             "[Console]::OutputEncoding=[Text.Encoding]::UTF8; $ProgressPreference='SilentlyContinue'; " + script],
            capture_output=True, timeout=timeout, creationflags=0x08000000, check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise RemoteError((f"Execution timed out ({timeout} s)" if get_lang()=="en" else f"انتهت مهلة التنفيذ ({timeout} ثانية)")) from exc
    out = done.stdout.decode("utf-8", "replace")
    err = done.stderr.decode("utf-8", "replace").strip()
    return ExecResult(_truncate(out + (("\n" + err) if err else "")), done.returncode != 0 or bool(err))


def _pypsrp_client(ip: str, username: str, password: str, *, ssl: bool, port: int, verify_tls: bool, timeout: int) -> Any:
    from pypsrp.client import Client

    return Client(ip, username=username, password=password, ssl=ssl, port=port, cert_validation=verify_tls,
                  auth="negotiate", connection_timeout=timeout, read_timeout=timeout, operation_timeout=max(5, timeout - 5),
                  encryption="auto")


# Replaceable in tests (no Windows target is reachable from CI).
client_factory: Callable[..., Any] = _pypsrp_client


def run_remote_powershell(ip: str, username: str, password: str, *, ssl: bool, port: int, verify_tls: bool,
                          script: str, timeout: int) -> ExecResult:
    try:
        client = client_factory(ip, username, password, ssl=ssl, port=port, verify_tls=verify_tls, timeout=timeout)
        output, streams, had_errors = client.execute_ps(script)
    except Exception as exc:  # noqa: BLE001 - mapped to an Arabic, actionable message
        raise RemoteError(_explain(exc)) from exc
    errors = "\n".join(str(e) for e in getattr(streams, "error", []) or [])
    text = (output or "") + (("\n" + errors) if errors else "")
    return ExecResult(_truncate(text), bool(had_errors))


def _explain(exc: Exception) -> str:
    name = type(exc).__name__
    text = str(exc)
    if "401" in text or "Authentication" in name or "credentials" in text.lower():
        return tr("فشل تسجيل الدخول على الجهاز: تحقق من اسم المستخدم وكلمة المرور وأن الحساب له صلاحية الإدارة عن بعد", "Sign-in to the device failed: check the username, password and that the account has remote-management rights")
    if "certificate" in text.lower() or "SSL" in name:
        return tr("فشل التحقق من شهادة HTTPS للجهاز. استخدم شهادة موثوقة أو عطّل التحقق لهذا الحساب إن كانت الشبكة موثوقة", "The device HTTPS certificate failed verification. Use a trusted certificate or disable verification for this account if the network is trusted")
    if "timed out" in text.lower() or "Timeout" in name:
        return tr("انتهت مهلة الاتصال بالجهاز عبر WinRM", "Connection to the device over WinRM timed out")
    if "refused" in text.lower() or "ConnectionError" in name or "Max retries" in text:
        return tr("تعذر الاتصال بخدمة WinRM على الجهاز. تأكد من تفعيلها (Enable-PSRemoting) وفتح المنفذ 5985/5986", "Could not connect to the WinRM service on the device. Ensure it is enabled (Enable-PSRemoting) and port 5985/5986 is open")
    return (f"Remote execution failed: {name}: {text[:300]}" if get_lang()=="en" else f"فشل التنفيذ عن بعد: {name}: {text[:300]}")


# --- SSH ---------------------------------------------------------------------------------

_SUDO_RE = re.compile(r"\bsudo\s+")


@dataclass
class HostKey:
    key_type: str
    fingerprint: str  # SHA256:base64 (OpenSSH style)


HostKeyLookup = Callable[[str, int], "HostKey | None"]
HostKeyStore = Callable[[str, int, "HostKey"], None]


def ssh_command(command: str, username: str) -> tuple[str, bool]:
    """Run guidance commands through a single privilege elevation.

    Returns (shell command, needs_password_on_stdin). All inner ``sudo`` are removed and the whole
    command runs as one ``sudo -S sh -c`` so a single password prompt covers nested calls.
    """
    import shlex

    inner = _SUDO_RE.sub("", command).strip()
    if not _SUDO_RE.search(command):
        return command, False
    if username == "root":
        return f"sh -c {shlex.quote(inner)}", False
    return f"sudo -S -p '' sh -c {shlex.quote(inner)}", True


def _fingerprint(key: Any) -> HostKey:
    import base64
    import hashlib

    digest = hashlib.sha256(key.asbytes()).digest()
    return HostKey(key.get_name(), "SHA256:" + base64.b64encode(digest).decode("ascii").rstrip("="))


def run_ssh(ip: str, port: int, username: str, password: str, command: str, timeout: int,
            lookup: HostKeyLookup, store: HostKeyStore) -> ExecResult:
    import socket as _socket

    import paramiko

    shell, needs_password = ssh_command(command, username)
    transport = None
    try:
        sock = _socket.create_connection((ip, port), timeout=timeout)
        transport = paramiko.Transport(sock)
        transport.start_client(timeout=timeout)
        presented = _fingerprint(transport.get_remote_server_key())
        known = lookup(ip, port)
        if known is None:
            store(ip, port, presented)  # trust on first use, pinned from now on
        elif known.fingerprint != presented.fingerprint:
            raise RemoteError(
                (f"Security warning: the SSH key for device {ip} changed ({known.fingerprint} -> {presented.fingerprint}). The device may have been reinstalled, or this may be spoofing. Not connecting. Delete the saved key after verifying, if the change was expected." if get_lang()=="en" else f"تحذير أمني: مفتاح SSH للجهاز {ip} تغيّر ({known.fingerprint} ← {presented.fingerprint}). قد يكون الجهاز أعيد تثبيته أو يوجد انتحال. لم يتم الاتصال. احذف المفتاح المحفوظ بعد التحقق إن كان التغيير متوقعاً.")
            )
        transport.auth_password(username, password)
        channel = transport.open_session(timeout=timeout)
        channel.settimeout(timeout)
        # `shell` is a command built only from fixed templates + strictly-validated parameters
        # (rasednet.remediation / rasednet.netadmin), run with a vaulted authorised account. Never free text.
        channel.exec_command(shell)  # nosec B601
        if needs_password:
            channel.sendall((password + "\n").encode("utf-8"))
        channel.shutdown_write()
        out = bytearray()
        err = bytearray()
        while True:
            if channel.recv_ready():
                out += channel.recv(65536)
            if channel.recv_stderr_ready():
                err += channel.recv_stderr(65536)
            if channel.exit_status_ready() and not channel.recv_ready() and not channel.recv_stderr_ready():
                break
            if len(out) + len(err) > MAX_OUTPUT * 2:
                break
            channel.status_event.wait(0.05)
        status = channel.recv_exit_status()
        text = out.decode("utf-8", "replace") + (("\n" + err.decode("utf-8", "replace")) if err else "")
        return ExecResult(_truncate(text.strip()), status != 0)
    except RemoteError:
        raise
    except paramiko.AuthenticationException as exc:
        raise RemoteError(tr("فشل تسجيل الدخول عبر SSH: تحقق من اسم المستخدم وكلمة المرور", "SSH sign-in failed: check the username and password")) from exc
    except TimeoutError as exc:
        raise RemoteError(tr("انتهت مهلة الاتصال عبر SSH", "SSH connection timed out")) from exc
    except (ConnectionRefusedError, OSError, paramiko.SSHException) as exc:
        raise RemoteError((f"Could not connect to the SSH service on the device: {type(exc).__name__}: {str(exc)[:200]}" if get_lang()=="en" else f"تعذر الاتصال بخدمة SSH على الجهاز: {type(exc).__name__}: {str(exc)[:200]}")) from exc
    finally:
        if transport is not None:
            transport.close()
